"""Куда можно вернуть человека после входа.

`?next=` приходит из ссылки «Это я» на карточке автора: аноним жмёт кнопку,
логинится и должен вернуться на ту же карточку. Без этого он заводит аккаунт и
оказывается на главной — страницу, ради которой пришёл, надо искать заново.

Принимаем ТОЛЬКО внутренний путь. С чужим адресом ручка входа становится
открытым редиректом: ссылка ведёт на наш домен, а после успешного входа человек
оказывается на чужом сайте — удобная подложка для фишинга.
"""
from __future__ import annotations

from src.core.config import settings


def safe_next(raw: str | None) -> str:
    """`/uz/author/ivanov-i-i` → абсолютный адрес фронта; всё чужое → главная."""
    front = settings.FRONTEND_URL.rstrip("/")
    path = (raw or "").strip()
    if not path.startswith("/"):
        return front
    # «//evil.com» и «/\evil.com» браузер читает как протокол-относительный
    # адрес, то есть как чужой хост, хотя строка начинается со слэша.
    if path[:2] in ("//", "/\\"):
        return front
    return front + path
